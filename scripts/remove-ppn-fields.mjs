// One-off migration: strip every PPN (input-VAT) field from the AP bill seed.
// The master-data generator only appends records beyond the current count, so
// it can't retrofit the 203 records already committed — this script does.
// Run via:
//
//     node scripts/remove-ppn-fields.mjs
//     node scripts/generate-journal-entries.mjs   # rebuild JEs without VAT-in
//
// Drops: ppn, ppnRate, fakturNo, taxReportingPeriod, taxReportingStatus.
// Because a bill's total was DPP + PPN, the gross figures collapse onto DPP:
// total = dpp, and sisa follows (0 stays 0 for settled bills). AR invoices are
// deliberately untouched — output VAT is a separate module.
//
// Idempotent: re-running a stripped seed is a no-op.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BILLS } from "../src/data/seed/bills.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const HEADER =
  `// AUTO-GENERATED by scripts/generate-master-data.mjs, then re-dated by\n` +
  `// scripts/regenerate-bills.mjs for AP-aging realism (deterministic).\n` +
  `// AP bills. \`vendor\` references vendors.js by id. The first 8 records are\n` +
  `// hand-curated demo anchors that the JE generator references; the rest are\n` +
  `// synthetic but reference the same vendor + CoA universe.\n` +
  `// No PPN: bills carry DPP only (see scripts/remove-ppn-fields.mjs).`;

const DROP = ["ppn", "ppnRate", "fakturNo", "taxReportingPeriod", "taxReportingStatus"];

let changed = 0;

const out = BILLS.map((b) => {
  const hadPpn = DROP.some((k) => k in b);
  if (hadPpn) changed++;

  // Keep items + audit last so the file stays readable.
  const { items, audit, ...head } = b;
  for (const k of DROP) delete head[k];

  const wasSettled = head.sisa === 0;
  head.total = head.dpp;
  head.sisa = wasSettled ? 0 : head.dpp;

  // Multi-currency vestiges, if present, tracked the gross figure too.
  if (head.original_total != null && head.fx_rate_used) {
    head.original_total = Math.round(head.dpp / head.fx_rate_used);
    head.original_sisa = wasSettled ? 0 : head.original_total;
  }

  return { ...head, items, audit };
});

const body = `${HEADER}\nexport const BILLS = [\n${
  out.map((r) => "  " + JSON.stringify(r).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:")).join(",\n")
},\n];\n`;

fs.writeFileSync(path.join(ROOT, "src/data/seed/bills.js"), body);
console.log(`Stripped PPN fields from ${changed}/${out.length} bills; total now = dpp.`);
