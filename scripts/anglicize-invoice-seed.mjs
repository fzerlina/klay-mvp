// One-off migration: move the AR invoice seed to English — enum values, audit
// action strings, line-item descriptions and units. The AP side has been English
// since the bills rework; AR was still carrying the original Bahasa enums, which
// also meant call sites testing `approval === "sent"` never matched anything.
// Run via:
//
//     node scripts/anglicize-invoice-seed.mjs
//
// The generator (scripts/generate-master-data.mjs) emits the English values too,
// so a regen and this migration agree.
//
// Idempotent: re-running an already-English seed is a no-op.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { INVOICES } from "../src/data/seed/invoices.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const HEADER =
  `// AUTO-GENERATED by scripts/generate-master-data.mjs (deterministic, seed 20250424).\n` +
  `// AR invoices. \`customer\` references customers.js by id. The first 8 records\n` +
  `// are hand-curated demo anchors that the JE generator references; the rest\n` +
  `// are synthetic but reference the same customer + CoA universe.\n` +
  `// No PPN: invoices carry DPP only (see scripts/remove-invoice-ppn.mjs).\n` +
  `// English enums and copy (see scripts/anglicize-invoice-seed.mjs).`;

const APPROVAL = { terkirim: "sent" };
const PAY = { lunas: "paid", belumbayar: "unpaid", sebagian: "partial" };
const AUDIT_ACTION = {
  "Invoice dibuat": "Invoice created",
  "Invoice dibuat otomatis oleh AI": "Invoice created automatically by AI",
  "Invoice dikirim": "Invoice sent",
  "Pembayaran diterima": "Payment received",
};
const UNIT = { paket: "pack", jasa: "service" }; // unit / kg / lot / set already read in English

// Line-item base names. The generator appends " — YYYY-MM" to most of them, so
// these are applied as prefix replacements.
const PRODUCT = {
  "Produk Divisi A - Paket Retail Premium":  "Division A — Premium Retail Pack",
  "Produk Divisi A - Paket Retail Standard": "Division A — Standard Retail Pack",
  "Produk Divisi A - Paket Retail":          "Division A — Retail Pack",
  "Produk Divisi A - Paket Premium":         "Division A — Premium Pack",
  "Produk Divisi B - Kemasan Standard":      "Division B — Standard Packaging",
  "Produk Divisi B - Kemasan Standar":       "Division B — Standard Packaging",
  "Produk Divisi B - Kemasan Premium":       "Division B — Premium Packaging",
  "Produk Divisi B - Paket Grosir":          "Division B — Wholesale Pack",
  "Jasa Setup & Training":                   "Setup & Training service",
  "Setup & Training":                        "Setup & Training",
  "Konsultasi implementasi":                 "Implementation consulting",
  "Bahan olahan kemasan":                    "Processed packaging material",
  "Tekstil produksi batch":                  "Textile production batch",
  "Elektronik produksi line":                "Electronics production line",
  "Furnitur kantor lengkap":                 "Complete office furniture",
};
// Longest first so "…Paket Retail Premium" wins over "…Paket Retail".
const PRODUCT_KEYS = Object.keys(PRODUCT).sort((a, b) => b.length - a.length);

function anglicizeDesc(desc) {
  if (!desc) return desc;
  for (const k of PRODUCT_KEYS) {
    if (desc.startsWith(k)) return PRODUCT[k] + desc.slice(k.length);
  }
  return desc;
}

let touched = 0;

const out = INVOICES.map((inv) => {
  const { items, audit, ...head } = inv;
  const before = JSON.stringify(inv);

  if (APPROVAL[head.approval]) head.approval = APPROVAL[head.approval];
  if (PAY[head.payStatus]) head.payStatus = PAY[head.payStatus];

  const nextItems = (items || []).map((it) => ({
    ...it,
    desc: anglicizeDesc(it.desc),
    unit: UNIT[it.unit] || it.unit,
  }));
  const nextAudit = (audit || []).map((a) => ({
    ...a,
    action: AUDIT_ACTION[a.action] || a.action,
  }));

  const next = { ...head, items: nextItems, audit: nextAudit };
  if (JSON.stringify(next) !== before) touched++;
  return next;
});

const body = `${HEADER}\nexport const INVOICES = [\n${
  out.map((r) => "  " + JSON.stringify(r).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:")).join(",\n")
},\n];\n`;

fs.writeFileSync(path.join(ROOT, "src/data/seed/invoices.js"), body);
console.log(`Anglicized ${touched}/${out.length} invoices.`);
