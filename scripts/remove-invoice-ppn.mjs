// One-off migration: strip output-VAT (PPN) from the AR invoice seed, mirroring
// what scripts/remove-ppn-fields.mjs did to the AP bill seed. The master-data
// generator only appends records beyond the current count, so it can't retrofit
// the 200 records already committed — this script does.
// Run via:
//
//     node scripts/remove-invoice-ppn.mjs
//
// Drops: ppn. Because an invoice's total was DPP + PPN, the gross figure
// collapses onto DPP: total = dpp.
//
// Idempotent: re-running a stripped seed is a no-op.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { INVOICES } from "../src/data/seed/invoices.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const HEADER =
  `// AUTO-GENERATED by scripts/generate-master-data.mjs (deterministic, seed 20250424).\n` +
  `// AR invoices. \`customer\` references customers.js by id. The first 8 records\n` +
  `// are hand-curated demo anchors that the JE generator references; the rest\n` +
  `// are synthetic but reference the same customer + CoA universe.\n` +
  `// No PPN: invoices carry DPP only (see scripts/remove-invoice-ppn.mjs).`;

const DROP = ["ppn", "ppnRate"];

let changed = 0;

const out = INVOICES.map((inv) => {
  if (DROP.some((k) => k in inv)) changed++;

  // Keep items + audit last so the file stays readable.
  const { items, audit, ...head } = inv;
  for (const k of DROP) delete head[k];

  head.total = head.dpp;

  return { ...head, items, audit };
});

const body = `${HEADER}\nexport const INVOICES = [\n${
  out.map((r) => "  " + JSON.stringify(r).replace(/"([a-zA-Z_][a-zA-Z0-9_]*)":/g, "$1:")).join(",\n")
},\n];\n`;

fs.writeFileSync(path.join(ROOT, "src/data/seed/invoices.js"), body);
console.log(`Stripped PPN from ${changed}/${out.length} invoices; total now = dpp.`);
